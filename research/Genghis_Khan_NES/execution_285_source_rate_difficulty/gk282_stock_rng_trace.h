#ifndef GK282_STOCK_RNG_TRACE_H
#define GK282_STOCK_RNG_TRACE_H
#include <stdint.h>
#include <stddef.h>
/* Native game research hook for authentic Mesen C289 entry / C2EB return traces.
 * A trace is caller-supplied evidence, not self-authenticating Mesen output.
 * The original private ROM is authenticated before C289 arithmetic is tested.
 * Does not create a game turn, prove seed chronology, or grant playable Spring.
 */
#define GK282_MAX_CALLS 8192u
typedef enum { GK282_OK=0,GK282_ARGUMENT=1,GK282_ROM=2,
 GK282_TRACE=3,GK282_SOURCE_PARITY=4,GK282_LIMIT=5 } Gk282Status;
typedef struct {
 uint32_t calls, rate_writes, seed_discontinuities, matching_rate_candidates;
 uint32_t first_matching_call, last_matching_call;
 uint64_t first_cycle,last_cycle;
 uint16_t last_written_rate;
 uint8_t scenario, observed_trace_claimed, validated_source_steps;
 /* EXEC0284: ALL previous C289 calls must be considered for a Rate write.
  * Counts are source-derived POSSIBLE associations, never causal proof.
  * Unique means only one (call,difficulty) pair in this bounded trace. */
 uint32_t possible_history_pairs, uniquely_matched_writes;
 uint32_t ambiguously_matched_writes, unmatched_writes;
 uint32_t first_possible_call, last_possible_call;
 uint32_t last_unique_call;
 uint8_t last_unique_difficulty;
 /* EXEC0285: difficulty is the current ORIGINAL native setup selection, not
  * a guessed historical Mesen difficulty. For each V event only earlier C
  * calls can match; do NOT filter out unrelated source-history possibilities.
  * Zero means the legacy all-five oracle did not select a difficulty. */
 uint8_t selected_difficulty;
 uint32_t selected_possible_pairs,selected_unique_writes;
 uint32_t selected_ambiguous_writes,selected_unmatched_writes;
 uint32_t selected_first_call,selected_last_call;
 uint8_t generated_first_spring; /* Always 0: not a source setup engine. */
} Gk282Report;
/* Text trace is generated by the supplied Mesen Lua probe; NEVER by the native
 * game and never automatically accepted as observed gameplay. Return atomic. */
Gk282Status gk282_check_c289_trace_for_difficulty(const char *private_rom,
 const char *private_trace,uint8_t selected_difficulty,Gk282Report *out);
/* Legacy all-five, unbiased research comparator, preserved for prior tests. */
Gk282Status gk282_check_c289_trace(const char *private_rom,
 const char *private_trace,Gk282Report *out);
#endif
