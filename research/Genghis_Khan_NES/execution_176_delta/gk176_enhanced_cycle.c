static Gk176Result source_seed(const Gk161EnhancedYear2 *y,
 const Gk116EnhancedAssign *sp,const Gk158EnhancedSummer *su,
 const Gk159EnhancedFall *fa,const Gk160EnhancedWinter *wi,
 const Gk79Checkpoint *original,Gk176EnhancedCycle *out){
 if(!out)return GK176_INPUT;
 if(!y||!sp||!su||!fa||!wi||!original||y->year>UINT16_MAX-5u||
    !gk161_attestation_intact(y,sp,su,fa,wi,original)||
    !y->budget.ended||y->budget.remaining) return GK176_SOURCE;
 Gk176EnhancedCycle e={0};
 e.mutable_world=y->mutable_world;
 e.budget=y->budget;
 if(gk71_next_season(&e.mutable_world,&e.budget,GK71_SUMMER)!=GK71_OK)
  return GK176_SOURCE;
 e.year=y->year;e.active=1u;e.season_index=0u;
 *out=e;return GK176_OK;
}
Gk176Result gk176_open(const Gk161EnhancedYear2 *y,
 const Gk116EnhancedAssign *sp,const Gk158EnhancedSummer *su,
 const Gk159EnhancedFall *fa,const Gk160EnhancedWinter *wi,
 const Gk79Checkpoint *original,Gk176EnhancedCycle *out){
 return source_seed(y,sp,su,fa,wi,original,out);
}
/* This private replay primitive cannot admit a forged receipt: every
 * transition is regenerated by the existing validated labor/order engine. */
static int replay_action(Gk176EnhancedCycle *next,
 const Gk116EnhancedAssign *sp,const Gk116LaborAction *action){
 Gk116Result r=gk116_worker_math(&next->mutable_world,&next->budget,
   sp->player_index,action->from,action->to,action->quantity);
 return r==GK116_OK;
}
int gk176_attestation_intact(const Gk176EnhancedCycle *e,
 const Gk161EnhancedYear2 *y,const Gk116EnhancedAssign *sp,
 const Gk158EnhancedSummer *su,const Gk159EnhancedFall *fa,
 const Gk160EnhancedWinter *wi,const Gk79Checkpoint *original){
 if(!e||!e->active||e->season_index>=GK176_MAX_SEASONS)return 0;
 Gk176EnhancedCycle replay={0};
 if(source_seed(y,sp,su,fa,wi,original,&replay)!=GK176_OK)return 0;
 for(unsigned season=0;season<=e->season_index;season++){
  Gk176SeasonReceipt const *src=&e->receipts[season];
  Gk176SeasonReceipt *dst=&replay.receipts[season];
  if(src->action_count>GK176_MAX_ACTIONS||src->pass_ended>1u)return 0;
  for(unsigned i=0;i<src->action_count;i++){
   if(!replay_action(&replay,sp,&src->actions[i]))return 0;
   dst->actions[dst->action_count++]=src->actions[i];
  }
  if(src->pass_ended){
   if(gk71_pass(&replay.budget)!=GK71_OK)return 0;
   dst->pass_ended=1u;
  }
  if(season<e->season_index){
   if(!replay.budget.ended)return 0;
   Gk71Season following=(Gk71Season)((replay.budget.season+1u)%4u);
   if(gk71_next_season(&replay.mutable_world,&replay.budget,following)!=GK71_OK)
    return 0;
   if(following==GK71_SPRING)replay.year++;
   replay.season_index++;
  }
 }
 return memcmp(&replay,e,sizeof replay)==0;
}
static Gk176Result map_worker(Gk116Result r){
 if(r==GK116_NO_WORKER)return GK176_NO_WORKER;
 if(r==GK116_NO_ORDERS)return GK176_NO_ORDERS;
 return GK176_INPUT;
}
Gk176Result gk176_transfer(Gk176EnhancedCycle *e,
 const Gk161EnhancedYear2 *y,const Gk116EnhancedAssign *sp,
 const Gk158EnhancedSummer *su,const Gk159EnhancedFall *fa,
 const Gk160EnhancedWinter *wi,const Gk79Checkpoint *original,
 uint8_t from,uint8_t to,uint16_t amount){
 if(!e)return GK176_INPUT;
 if(!gk176_attestation_intact(e,y,sp,su,fa,wi,original))return GK176_SOURCE;
 const Gk176SeasonReceipt *r=&e->receipts[e->season_index];
 if(e->budget.ended||r->action_count>=GK176_MAX_ACTIONS||r->pass_ended)
  return GK176_NO_ORDERS;
 Gk176EnhancedCycle next=*e;
 Gk116Result status=gk116_worker_math(&next.mutable_world,&next.budget,
   sp->player_index,from,to,amount);
 if(status!=GK116_OK)return map_worker(status);
 Gk116LaborAction action={0};action.from=from;action.to=to;action.quantity=amount;
 next.receipts[next.season_index].actions[next.receipts[next.season_index].action_count++]=action;
 if(!gk176_attestation_intact(&next,y,sp,su,fa,wi,original))return GK176_SOURCE;
 *e=next;return GK176_OK;
}
Gk176Result gk176_pass(Gk176EnhancedCycle *e,
 const Gk161EnhancedYear2 *y,const Gk116EnhancedAssign *sp,
 const Gk158EnhancedSummer *su,const Gk159EnhancedFall *fa,
 const Gk160EnhancedWinter *wi,const Gk79Checkpoint *original){
 if(!e)return GK176_INPUT;
 if(!gk176_attestation_intact(e,y,sp,su,fa,wi,original))return GK176_SOURCE;
 if(e->budget.ended)return GK176_NO_ORDERS;
 Gk176EnhancedCycle next=*e;
 if(gk71_pass(&next.budget)!=GK71_OK)return GK176_SOURCE;
 next.receipts[next.season_index].pass_ended=1u;
 if(!gk176_attestation_intact(&next,y,sp,su,fa,wi,original))return GK176_SOURCE;
 *e=next;return GK176_OK;
}
Gk176Result gk176_advance(Gk176EnhancedCycle *e,
 const Gk161EnhancedYear2 *y,const Gk116EnhancedAssign *sp,
 const Gk158EnhancedSummer *su,const Gk159EnhancedFall *fa,
 const Gk160EnhancedWinter *wi,const Gk79Checkpoint *original){
 if(!e)return GK176_INPUT;
 if(!gk176_attestation_intact(e,y,sp,su,fa,wi,original))return GK176_SOURCE;
 if(!e->budget.ended)return GK176_NO_ORDERS;
 if(e->season_index+1u==GK176_MAX_SEASONS)return GK176_END;
 Gk176EnhancedCycle next=*e;
 Gk71Season season=(Gk71Season)((next.budget.season+1u)%4u);
 if(gk71_next_season(&next.mutable_world,&next.budget,season)!=GK71_OK)
  return GK176_SOURCE;
 if(season==GK71_SPRING)next.year++;
 next.season_index++;
 if(!gk176_attestation_intact(&next,y,sp,su,fa,wi,original))return GK176_SOURCE;
 *e=next;return GK176_OK;
}
